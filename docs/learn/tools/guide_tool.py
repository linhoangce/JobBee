"""Keep the learner guide's code blocks identical to the real code, and prove the guide works.

Every code block in docs/learn/NN-*.md that shows real code sits between markers:

    <!-- code: backend/app/config.py -->              whole file
    <!-- code: backend/app/apply/runs.py lines=1-120 -->   consecutive part of a file
    <!-- code: backend/tests/test_health.py collapsed -->  whole file inside <details>
    ...generated heading + fenced code...
    <!-- /code -->

Blocks the guide writes by hand (they are not in the repo, or not in their final form yet):

    <!-- temp: backend/app/main.py -->      a temporary version, replaced in a later stage
    <!-- practice: practice/try_tools.py --> a practice file that is not part of JobBee
    ```python
    ...
    ```
    <!-- /temp -->   (or <!-- /practice -->)

Hidden checks that `rebuild` runs at that point of the guide:

    <!-- verify: backend | python -m pytest -q tests/test_health.py -->
    <!-- verify: frontend | npm run build -->

Commands:
    python guide_tool.py fill [FILE...]  regenerate code blocks from the repo (all stage files by default)
    python guide_tool.py check [FILE...] verify markers, links and that blocks are up to date; with no
                                         files it also checks every repo file is shown exactly once
    python guide_tool.py rebuild OUT     rebuild the project from the guide alone, running every
                                         verify step, then compare the result with the repo
"""

from __future__ import annotations

import argparse
import filecmp
import os
import re
import shutil
import subprocess
import sys
from dataclasses import dataclass
from pathlib import Path

LEARN = Path(__file__).resolve().parent.parent
REPO = LEARN.parent.parent

CODE_OPEN = re.compile(r"^<!-- code: (\S+)((?: [a-z]+(?:=\S+)?)*) -->$")
CODE_CLOSE = "<!-- /code -->"
HAND_OPEN = re.compile(r"^<!-- (temp|practice): (\S+) -->$")
HAND_CLOSE = re.compile(r"^<!-- /(temp|practice) -->$")
VERIFY = re.compile(r"^<!-- verify: (backend|frontend|root) \| (.+) -->$")
FENCE = re.compile(r"^(\s*)(`{3,}|~{3,})(\S*)\s*$")
LINK = re.compile(r"\]\(([^)\s]+)\)")

LANG = {
    ".py": "python", ".ts": "ts", ".tsx": "tsx", ".css": "css", ".md": "markdown",
    ".toml": "toml", ".ini": "ini", ".json": "json", ".html": "html", ".txt": "text",
    ".mako": "mako", ".ps1": "powershell", ".example": "ini",
}

# Files the guide does not need to show (generated by tools, or documentation).
NOT_COVERED = re.compile(r"^(docs/|README\.md$|frontend/package-lock\.json$)")


def stage_files() -> list[Path]:
    return sorted(p for p in LEARN.glob("[0-9][0-9]-*.md"))


def repo_files() -> list[str]:
    out = subprocess.run(["git", "ls-files"], cwd=REPO, capture_output=True, text=True, check=True)
    return [f for f in out.stdout.splitlines() if not NOT_COVERED.match(f)]


def read_lines(rel: str) -> list[str]:
    return (REPO / rel).read_text(encoding="utf-8").split("\n")[:-1]


def fence_for(text: str) -> str:
    longest = max((len(m) for m in re.findall(r"`+", text)), default=0)
    return "`" * max(3, longest + 1)


@dataclass
class CodeRef:
    path: str
    start: int
    end: int
    total: int
    collapsed: bool


def parse_code_marker(line: str) -> CodeRef | None:
    m = CODE_OPEN.match(line)
    if not m:
        return None
    path, opts = m.group(1), m.group(2).split()
    total = len(read_lines(path)) if (REPO / path).is_file() else 0
    start, end, collapsed = 1, total, False
    for opt in opts:
        if opt.startswith("lines="):
            a, b = opt[6:].split("-")
            start, end = int(a), int(b)
        elif opt == "collapsed":
            collapsed = True
        else:
            raise ValueError(f"unknown option {opt!r} in {line}")
    return CodeRef(path, start, end, total, collapsed)


def render_block(ref: CodeRef) -> list[str]:
    lines = read_lines(ref.path)[ref.start - 1 : ref.end]
    body = "\n".join(lines)
    fence = fence_for(body)
    lang = LANG.get(Path(ref.path).suffix, "text")
    if ref.start == 1 and ref.end == ref.total:
        where = f"whole file, {ref.total} lines"
    else:
        where = f"lines {ref.start}–{ref.end} of {ref.total}"
    head = f"**`{ref.path}`** ({where})"
    out: list[str] = []
    if ref.collapsed:
        out += ["<details>", f"<summary><code>{ref.path}</code> ({where})</summary>", ""]
    else:
        out += [head, ""]
    out += [f"{fence}{lang}", *lines, fence]
    if ref.collapsed:
        out += ["", "</details>"]
    return out


def fill_file(md: Path) -> bool:
    src = md.read_text(encoding="utf-8").split("\n")
    out: list[str] = []
    i = 0
    while i < len(src):
        line = src[i]
        ref = parse_code_marker(line)
        if ref is None:
            out.append(line)
            i += 1
            continue
        j = i + 1
        while j < len(src) and src[j] != CODE_CLOSE:
            j += 1
        if j == len(src):
            raise SystemExit(f"{md.name}:{i + 1}: missing {CODE_CLOSE}")
        out += [line, *render_block(ref), CODE_CLOSE]
        i = j + 1
    new = "\n".join(out)
    if new != "\n".join(src):
        md.write_text(new, encoding="utf-8")
        return True
    return False


@dataclass
class Item:
    kind: str  # code | temp | practice | verify
    stage: str
    line: int
    path: str = ""
    start: int = 0
    end: int = 0
    total: int = 0
    content: str = ""
    where: str = ""
    command: str = ""


def parse(md: Path) -> tuple[list[Item], list[str]]:
    items: list[Item] = []
    problems: list[str] = []
    src = md.read_text(encoding="utf-8").split("\n")
    i = 0
    in_fence = None
    while i < len(src):
        line = src[i]
        fm = FENCE.match(line)
        if in_fence is None and fm:
            in_fence = fm.group(2)
            if not fm.group(3):
                problems.append(f"{md.name}:{i + 1}: code fence without a language tag")
            i += 1
            continue
        if in_fence is not None:
            if fm and fm.group(2) == in_fence and not fm.group(3):
                in_fence = None
            i += 1
            continue
        try:
            ref = parse_code_marker(line)
        except ValueError as exc:
            problems.append(f"{md.name}:{i + 1}: {exc}")
            ref = None
        if ref is not None:
            if not (REPO / ref.path).is_file():
                problems.append(f"{md.name}:{i + 1}: no such repo file {ref.path}")
            j = i + 1
            while j < len(src) and src[j] != CODE_CLOSE:
                j += 1
            if j == len(src):
                problems.append(f"{md.name}:{i + 1}: missing {CODE_CLOSE}")
                break
            if (REPO / ref.path).is_file() and src[i + 1 : j] != render_block(ref):
                problems.append(f"{md.name}:{i + 1}: code block out of date (run fill): {ref.path}")
            items.append(Item("code", md.name, i + 1, ref.path, ref.start, ref.end, ref.total))
            i = j + 1
            continue
        hm = HAND_OPEN.match(line)
        if hm:
            kind, path = hm.group(1), hm.group(2)
            j = i + 1
            while j < len(src) and not HAND_CLOSE.match(src[j]):
                j += 1
            if j == len(src):
                problems.append(f"{md.name}:{i + 1}: missing <!-- /{kind} -->")
                break
            block = src[i + 1 : j]
            starts = [k for k, b in enumerate(block) if FENCE.match(b)]
            if len(starts) < 2:
                problems.append(f"{md.name}:{i + 1}: {kind} block needs exactly one fenced block")
            else:
                body = block[starts[0] + 1 : starts[-1]]
                items.append(Item(kind, md.name, i + 1, path, content="\n".join(body) + "\n"))
            i = j + 1
            continue
        vm = VERIFY.match(line)
        if vm:
            items.append(Item("verify", md.name, i + 1, where=vm.group(1), command=vm.group(2)))
        elif line.startswith("<!-- ") and any(
            line.startswith(f"<!-- {k}") for k in ("code", "temp", "practice", "verify", "/")
        ):
            problems.append(f"{md.name}:{i + 1}: malformed marker: {line}")
        for link in LINK.findall(line):
            if re.match(r"^[a-z]+:", link) or link.startswith("#"):
                continue
            if not (md.parent / link.split("#")[0]).resolve().exists():
                problems.append(f"{md.name}:{i + 1}: broken link: {link}")
        i += 1
    return items, problems


def check(only: list[Path] | None = None) -> int:
    problems: list[str] = []
    parts: dict[str, list[Item]] = {}
    for md in only or stage_files():
        items, probs = parse(md)
        problems += probs
        for it in items:
            if it.kind == "code":
                parts.setdefault(it.path, []).append(it)
    for path, its in parts.items():
        expect = 1
        for it in its:
            if it.start != expect:
                problems.append(
                    f"{it.stage}:{it.line}: {path} part starts at line {it.start}, expected {expect}"
                )
            expect = it.end + 1
        total = its[-1].total
        if only and its[0].start != 1:
            continue  # the earlier parts of this file live in a stage that was not checked
        if expect - 1 != total and not only:
            problems.append(f"{path}: parts end at line {expect - 1} but the file has {total} lines")
    missing = [] if only else [f for f in repo_files() if f not in parts]
    for f in missing:
        problems.append(f"not shown anywhere in the guide: {f}")
    for p in problems:
        print(p)
    shown = len([f for f in repo_files() if f in parts])
    print(f"{len(only or stage_files())} stage file(s), {shown}/{len(repo_files())} repo files shown, "
          f"{len(problems)} problem(s)")
    return 1 if problems else 0


def rebuild(out: Path, python: str, node_modules: Path | None, stop_after: str | None) -> int:
    if out.exists():
        shutil.rmtree(out)
    out.mkdir(parents=True)
    written: dict[str, str] = {}
    pieces: dict[str, list[str]] = {}
    failures = 0
    for md in stage_files():
        items, probs = parse(md)
        if probs:
            print("\n".join(probs))
            return 1
        print(f"== {md.name}")
        for it in items:
            if it.kind == "code":
                chunk = read_lines(it.path)[it.start - 1 : it.end]
                pieces.setdefault(it.path, []).extend(chunk)
                target = out / it.path
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_text("\n".join(pieces[it.path]) + "\n", encoding="utf-8")
                written[it.path] = "code"
            elif it.kind in ("temp", "practice"):
                target = out / it.path
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_text(it.content, encoding="utf-8")
                written[it.path] = it.kind
            elif it.kind == "verify":
                cwd = out / ("backend" if it.where == "backend" else "frontend" if it.where == "frontend" else "")
                if it.where == "frontend" and node_modules and not (cwd / "node_modules").exists():
                    (cwd / "node_modules").symlink_to(node_modules)
                cmd = re.sub(r"^((?:\w+=\S*\s+)*)python\b", lambda m: m.group(1) + python, it.command)
                env = {**os.environ, "PYTHONPATH": str(out / "backend"), "PYTHONDONTWRITEBYTECODE": "1"}
                res = subprocess.run(cmd, shell=True, cwd=cwd, env=env, capture_output=True, text=True)
                status = "ok" if res.returncode == 0 else f"FAILED ({res.returncode})"
                print(f"   verify [{it.where}] {it.command} -> {status}")
                if res.returncode != 0:
                    failures += 1
                    print("      " + "\n      ".join((res.stdout + res.stderr).strip().splitlines()[-25:]))
        if stop_after and md.name.startswith(stop_after):
            break
    if stop_after:
        print(f"stopped after {stop_after}; {failures} verify failure(s)")
        return 1 if failures else 0
    # The finished project must equal the repo, file for file.
    mismatched = []
    for f in repo_files():
        rebuilt = out / f
        if not rebuilt.is_file():
            mismatched.append(f"missing after rebuild: {f}")
        elif not filecmp.cmp(rebuilt, REPO / f, shallow=False):
            mismatched.append(f"differs from repo after rebuild: {f} (last written as {written.get(f)})")
    leftovers = [p for p, kind in written.items() if kind == "temp" and p not in repo_files()]
    for p in leftovers:
        mismatched.append(f"temporary file never replaced or removed: {p}")
    print("\n".join(mismatched))
    print(f"rebuild: {failures} verify failure(s), {len(mismatched)} file mismatch(es)")
    return 1 if failures or mismatched else 0


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    fl = sub.add_parser("fill")
    fl.add_argument("files", nargs="*", type=Path)
    ck = sub.add_parser("check")
    ck.add_argument("files", nargs="*", type=Path)
    rb = sub.add_parser("rebuild")
    rb.add_argument("out", type=Path)
    rb.add_argument("--python", default=sys.executable)
    rb.add_argument("--node-modules", type=Path, default=REPO / "frontend" / "node_modules")
    rb.add_argument("--stop-after", help="stage number prefix, e.g. 07")
    args = ap.parse_args()
    if args.cmd == "fill":
        targets = [f.resolve() for f in args.files] or stage_files()
        changed = [md.name for md in targets if fill_file(md)]
        print(f"filled {len(changed)} file(s): {', '.join(changed)}" if changed else "all blocks up to date")
        return 0
    if args.cmd == "check":
        return check([f.resolve() for f in args.files] or None)
    nm = args.node_modules if args.node_modules.exists() else None
    return rebuild(args.out.resolve(), args.python, nm, args.stop_after)


if __name__ == "__main__":
    sys.exit(main())
